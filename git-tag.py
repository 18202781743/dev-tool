def findCommitByChangelogBlame(changelog_version):
    """使用 git blame 和时间信息来查找 changelog 版本对应的提交"""
    try:
        # 获取 changelog 版本的详细信息，包括时间
        changelog_info = subprocess.run(
            ["dpkg-parsechangelog", "--format", "rfc822"],
            capture_output=True,
            text=True
        )
        
        if changelog_info.returncode != 0:
            logger.warning("Could not get detailed changelog info")
            return None
            
        # 解析 changelog 信息，获取时间戳
        changelog_lines = changelog_info.stdout.split('\n')
        changelog_date = None
        for line in changelog_lines:
            if line.startswith('Date:'):
                changelog_date = line.split('Date:', 1)[1].strip()
                break
        
        if not changelog_date:
            logger.warning("Could not find date in changelog")
            return None
            
        logger.info(f"Found changelog date for {changelog_version}: {changelog_date}")
        
        # 解析 changelog 日期为时间戳 (将 RFC2822 格式转换为时间戳)
        import email.utils
        try:
            changelog_timestamp = email.utils.parsedate_to_datetime(changelog_date).timestamp()
            logger.info(f"Parsed changelog timestamp: {changelog_timestamp}")
        except Exception as e:
            logger.warning(f"Could not parse changelog date '{changelog_date}': {e}")
            # 如果时间解析失败，回退到字符串匹配
            return _fallbackStringMatch(changelog_version)
        
        # 使用 git blame 查找 debian/changelog 文件中包含版本号的行
        blame_result = subprocess.run(
            ["git", "blame", "--porcelain", "debian/changelog"],
            capture_output=True,
            text=True
        )
        
        if blame_result.returncode != 0:
            logger.warning("Could not run git blame on debian/changelog")
            return None
            
        # 解析 blame 输出，查找与时间戳最接近的包含版本号的行
        lines = blame_result.stdout.split('\n')
        current_commit = None
        current_author_time = None
        best_match_commit = None
        best_time_diff = float('inf')
        
        for i, line in enumerate(lines):
            # porcelain 格式解析
            if line and not line.startswith('\t'):
                if ' ' in line:
                    parts = line.split(' ')
                    if len(parts) >= 1 and len(parts[0]) == 40 and all(c in '0123456789abcdef' for c in parts[0].lower()):
                        # 这是一个 commit hash 行
                        current_commit = parts[0]
                        current_author_time = None
                elif line.startswith('author-time ') and current_commit:
                    # 获取作者时间
                    try:
                        current_author_time = int(line.split('author-time ')[1])
                    except (IndexError, ValueError):
                        current_author_time = None
            elif line.startswith('\t') and current_commit and current_author_time:
                # 这是实际的内容行
                content = line[1:]  # 去掉开头的 tab
                # 检查是否包含版本号（在 debian/changelog 格式中）
                if f"({changelog_version})" in content and ('unstable' in content or 'stable' in content):
                    # 计算时间差
                    time_diff = abs(current_author_time - changelog_timestamp)
                    logger.debug(f"Found potential match: commit {current_commit}, time diff: {time_diff}s")
                    logger.debug(f"Content: {content.strip()}")
                    
                    # 如果时间差更小，更新最佳匹配
                    if time_diff < best_time_diff:
                        best_time_diff = time_diff
                        best_match_commit = current_commit
                        logger.debug(f"New best match: {current_commit} (time diff: {time_diff}s)")
        
        if best_match_commit:
            logger.info(f"Found best time-matched commit for changelog version {changelog_version}: {best_match_commit}")
            logger.info(f"Time difference: {best_time_diff}s")
            return best_match_commit
        else:
            logger.warning(f"Could not find time-matched commit for changelog version {changelog_version}")
            # 回退到字符串匹配
            return _fallbackStringMatch(changelog_version)
        
    except Exception as e:
        logger.error(f"Error in findCommitByChangelogBlame: {str(e)}")
        return None

def _fallbackStringMatch(changelog_version):
    """回退到字符串匹配的方法"""
    try:
        logger.info(f"Falling back to string matching for version {changelog_version}")
        
        blame_result = subprocess.run(
            ["git", "blame", "--porcelain", "debian/changelog"],
            capture_output=True,
            text=True
        )
        
        if blame_result.returncode != 0:
            return None
            
        lines = blame_result.stdout.split('\n')
        current_commit = None
        
        for i, line in enumerate(lines):
            if line and not line.startswith('\t') and ' ' in line:
                parts = line.split(' ')
                if len(parts) >= 1 and len(parts[0]) == 40 and all(c in '0123456789abcdef' for c in parts[0].lower()):
                    current_commit = parts[0]
            elif line.startswith('\t') and current_commit:
                content = line[1:]
                if f"({changelog_version})" in content and ('unstable' in content or 'stable' in content):
                    logger.info(f"Found commit using string match: {current_commit}")
                    logger.info(f"Matching line: {content.strip()}")
                    return current_commit
        
        return None
    except Exception as e:
        logger.error(f"Error in fallback string match: {str(e)}")
        return None
        
    except Exception as e:
        logger.error(f"Error in findCommitByChangelogBlame: {str(e)}")
        return None

def findLastTaggedVersion():
    """查找最新的已经打了tag的版本，优先使用changelog中的版本"""
    try:
        # 首先尝试从 changelog 获取版本
        try:
            changelog_result = subprocess.run(
                "dpkg-parsechangelog --show-field Version",
                shell=True,
                check=True,
                capture_output=True,
                text=True
            )
            changelog_version = changelog_result.stdout.strip()
            logger.info(f"Found version from changelog: {changelog_version}")
            
            # 使用 git blame 方法查找对应的提交
            commit_hash = findCommitByChangelogBlame(changelog_version)
            if commit_hash:
                logger.info(f"Found commit for changelog version {changelog_version}: {commit_hash}")
                # 返回提交hash，用于后续的commit信息获取
                return commit_hash
            else:
                # 如果找不到对应的提交，仍然返回 changelog 版本
                logger.info(f"Using changelog version as fallback: {changelog_version}")
                return changelog_version
            
        except subprocess.CalledProcessError:
            logger.warning("Could not get version from changelog, falling back to git tags")
        
        # 如果 changelog 方法失败，回退到 git tags
        tags_result = subprocess.run(
            ["git", "tag", "-l", "--sort=-version:refname"],
            capture_output=True,
            text=True
        )
        
        if tags_result.returncode == 0 and tags_result.stdout.strip():
            latest_tag = tags_result.stdout.strip().split('\n')[0]
            logger.info(f"Found latest git tag as fallback: {latest_tag}")
            return latest_tag
        else:
            logger.warning("No git tags found")
            return None
            
    except Exception as e:
        logger.error(f"Error finding latest tagged version: {str(e)}")
        return None

def fetchLastTag():
    """获取最新的已打tag的版本，用于生成下一个版本"""
    try:
        # Fetch from origin
        fetch_result = subprocess.run(
            "git fetch origin",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )
        logger.debug(f"Fetch output: {fetch_result.stdout}")

        # 直接获取最新的 git tag
        latest_tag = findLastTaggedVersion()
        if latest_tag:
            logger.info(f"Using latest git tag: {latest_tag}")
            return latest_tag
        else:
            logger.error("Could not find any git tag")
            return None
        
    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to fetch origin: {e.stderr}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error in fetchLastTag: {str(e)}")
        return None

def fetchLastGitTag():
    """从 Git 提交历史获取最新的 tag，用于版本自动生成"""
    try:
        # Get last tag from git tags
        git_tag_result = subprocess.run(
            "git describe --tags --abbrev=0",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )
        git_version = git_tag_result.stdout.strip()
        logger.info(f"Found latest git tag for version generation: {git_version}")
        return git_version
        
    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to get git tag for version generation: {e.stderr}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error in fetchLastGitTag: {str(e)}")
        return None

def autoGeneratedTagByLastTag(lastTag):
    """根据最新的 tag 生成下一个版本"""
    # 检查 lastTag 是否是 commit hash（长度为40的十六进制字符串）
    if len(lastTag) == 40 and all(c in '0123456789abcdef' for c in lastTag.lower()):
        # lastTag 是 commit hash，需要从 changelog 获取版本号
        logger.info(f"lastTag appears to be a commit hash: {lastTag}")
        try:
            changelog_result = subprocess.run(
                "dpkg-parsechangelog --show-field Version",
                shell=True,
                check=True,
                capture_output=True,
                text=True
            )
            changelog_version = changelog_result.stdout.strip()
            logger.info(f"Using changelog version for version generation: {changelog_version}")
            base_tag = changelog_version
        except subprocess.CalledProcessError as e:
            logger.warning(f"Failed to get changelog version, falling back to git tag: {e.stderr}")
            git_tag = fetchLastGitTag()
            if git_tag:
                base_tag = git_tag
            else:
                raise ValueError("Could not determine base version for generation")
    else:
        # lastTag 是版本号，直接使用
        logger.info(f"Using provided version for version generation: {lastTag}")
        base_tag = lastTag
    
    # 处理 Debian 版本格式，可能包含 epoch (如 1:6.1.15)
    epoch = ""
    version_part = base_tag
    
    if ':' in base_tag:
        epoch_part, version_part = base_tag.split(':', 1)
        epoch = epoch_part + ":"
        logger.info(f"Detected Debian epoch format: epoch='{epoch_part}', version='{version_part}'")
    
    increment_part = 'patch'  # 默认递增部分为 'patch' {major}.{minor}.{patch}
    parts = version_part.split('.')
    if len(parts) != 3:
        raise ValueError(f"无效的版本号格式 '{version_part}'，应为 major.minor.patch")

    try:
        major = int(parts[0])
        minor = int(parts[1])
        patch = int(parts[2])
    except ValueError:
        raise ValueError(f"版本号各部分必须为整数 '{version_part}'")
        
    if increment_part == 'patch':
        patch += 1
    elif increment_part == 'minor':
        minor += 1
        patch = 0
    elif increment_part == 'major':
        major += 1
        minor = 0
        patch = 0
    else:
        raise ValueError(f"无效的递增部分 '{increment_part}'，应为 'major', 'minor', 或 'patch'")

    new_version = f"{epoch}{major}.{minor}.{patch}"
    logger.info(f"Generated new version: {new_version} (base: {base_tag})")
    return new_version

def initTagPR():
    try:
        # Git operations
        subprocess.run(
            "git fetch origin",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )
        
        subprocess.run(
            ["git", "reset", "--hard", f"origin/{argsInfo.projectBranch}"],
            check=True,
            capture_output=True,
            text=True
        )
        
        subprocess.run(
            f"git checkout -B dev-changelog origin/{argsInfo.projectBranch}",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )

        # Set DEBEMAIL environment variable
        os.environ["DEBEMAIL"] = argsInfo.debEmail

        lastTag = fetchLastTag()
        logger.info(f"Last Tag: {lastTag}")

        if argsInfo.autoGeneratedProjectTag:
            argsInfo.projectTag = autoGeneratedTagByLastTag(lastTag)
        
        logger.info(f"Project Tag: {argsInfo.projectTag}")

        # Get commit info
        commit_result = subprocess.run(
            ["git", "log", "--pretty=format:%s", "--no-merges", f"{lastTag}..HEAD"],
            check=True,
            capture_output=True,
            text=True
        )
        commitInfo = commit_result.stdout
        if not commitInfo:
            commitInfo = f"Release {argsInfo.projectTag}"

        logger.info(f"Changelog Info: {commitInfo}")

        # Process changelog
        with subprocess.Popen(
            ["xargs", "-d", "\n", "-I", "{}", "dch", "-v", argsInfo.projectTag, "{}"],
            stdin=subprocess.PIPE,
            text=True
        ) as dch_process:
            dch_process.communicate(input=commitInfo)

        subprocess.run(
            "dch -r ''",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )

        # Commit changes
        subprocess.run(
            ["git", "commit", "-a", "-m", f"chore: bump version to {argsInfo.projectTag}\n\nupdate changelog to {argsInfo.projectTag}"],
            check=True,
            capture_output=True,
            text=True
        )

    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to initialize tag PR: {e.stderr}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error in initTagPR: {str(e)}")
        raise

def createTagPR():
    try:
        # Check if forked repo exists
        fork_check = subprocess.run(
            ["gh", "repo", "view", f"{argsInfo.githubID}/{argsInfo.projectName}"],
            capture_output=True,
            text=True
        )
        
        if fork_check.returncode != 0:
            # Fork the repo if not exists
            logger.info(f"Forking repository {argsInfo.projectOrg}/{argsInfo.projectName}")
            fork_result = subprocess.run(
                ["gh", "repo", "fork", f"{argsInfo.projectOrg}/{argsInfo.projectName}", "--clone=false"],
                check=True,
                capture_output=True,
                text=True
            )
            logger.debug(f"Fork output: {fork_result.stdout}")

        # Push to github
        push_result = subprocess.run(
            "git push github dev-changelog -f",
            shell=True,
            check=True,
            capture_output=True,
            text=True
        )
        logger.debug(f"Push output: {push_result.stdout}")

        # Prepare PR creation command
        args = [
            "gh", "pr", "create",
            "--repo", f"{argsInfo.projectOrg}/{argsInfo.projectName}",
            "--head", f"{argsInfo.githubID}:dev-changelog",
            "--base", argsInfo.projectBranch,
            "--title", f"chore: bump version to {argsInfo.projectTag}",
            "--body", f"update changelog to {argsInfo.projectTag}"
        ]
        
        # Add reviewers if specified
        if argsInfo.projectReviewers:
            reviewers = []
            for value in argsInfo.projectReviewers:
                reviewers.extend(['--reviewer', value])
            args.extend(reviewers)
        
        # Create PR
        pr_result = subprocess.run(
            args,
            check=True,
            capture_output=True,
            text=True
        )
        
        # 提取PR链接
        pr_url = pr_result.stdout.strip()
        if pr_url:
            logger.info(f"✅ Successfully created PR for tag {argsInfo.projectTag}")
            logger.info(f"🔗 PR链接: {pr_url}")
            print(f"\n🚀 PR已创建! 请查看: {pr_url}\n")
        else:
            logger.info(f"Successfully created PR for tag {argsInfo.projectTag}")
        
        logger.debug(f"PR creation output: {pr_result.stdout}")
        
    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to create tag PR: {e.stderr}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error in createTagPR: {str(e)}")
        raise

def mergePR():
    try:
        merge_result = subprocess.run(
            ["gh", "pr", "merge", "--repo", f"{argsInfo.projectOrg}/{argsInfo.projectName}", "-r", f"{argsInfo.githubID}:dev-changelog"],
            check=True,
            capture_output=True,
            text=True
        )
        logger.info("✅ Successfully merged PR")
        
        # 获取PR链接信息
        try:
            pr_info = subprocess.run(
                ["gh", "pr", "view", "--repo", f"{argsInfo.projectOrg}/{argsInfo.projectName}", f"{argsInfo.githubID}:dev-changelog", "--json", "url"],
                capture_output=True,
                text=True
            )
            if pr_info.returncode == 0:
                import json
                pr_data = json.loads(pr_info.stdout)
                pr_url = pr_data.get('url', '')
                if pr_url:
                    logger.info(f"🔗 已合并的PR: {pr_url}")
                    print(f"\n🎉 PR已成功合并! PR链接: {pr_url}\n")
        except:
            pass  # 如果获取失败，不影响主流程
            
        logger.debug(f"Merge output: {merge_result.stdout}")
    except subprocess.CalledProcessError as e:
        logger.error(f"Failed to merge PR: {e.stderr}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error in mergePR: {str(e)}")
        raise

def runRelease():
    """执行GitHub Auto Release workflow"""
    try:
        # 检查gh命令是否可用
        gh_check = subprocess.run(
            ["gh", "--version"],
            capture_output=True,
            text=True
        )
        if gh_check.returncode != 0:
            logger.error("GitHub CLI (gh) is not installed or not available")
            logger.error("Please install GitHub CLI: https://cli.github.com/")
            raise SystemExit(1)

        # 检查是否已登录GitHub
        auth_check = subprocess.run(
            ["gh", "auth", "status"],
            capture_output=True,
            text=True
        )
        if auth_check.returncode != 0:
            logger.error("Not logged in to GitHub")
            logger.error("Please run: gh auth login")
            raise SystemExit(1)

        # 设置默认仓库
        repo_name = f"{argsInfo.projectOrg}/{argsInfo.projectName}"
        logger.info(f"Setting default repository to {repo_name}")

        set_default_result = subprocess.run(
            ["gh", "repo", "set-default", repo_name],
            capture_output=True,
            text=True
        )
        if set_default_result.returncode != 0:
            logger.warning(f"Could not set default repository: {set_default_result.stderr}")
            logger.info("Continuing with explicit repository specification...")

        # 触发Auto Release workflow
        logger.info(f"Triggering 'Auto Release' workflow for {repo_name}")

        workflow_cmd = ["gh", "workflow", "run", "Auto Release"]
        if set_default_result.returncode != 0:
            workflow_cmd.extend(["--repo", repo_name])

        workflow_result = subprocess.run(
            workflow_cmd,
            capture_output=True,
            text=True
        )

        if workflow_result.returncode == 0:
            logger.info("✅ Successfully triggered 'Auto Release' workflow")
            logger.info("🚀 The workflow will automatically create tags and PRs")
            print(f"\n🎉 Auto Release workflow triggered for {repo_name}!")
            print("📋 You can check the workflow status at:")
            print(f"   https://github.com/{repo_name}/actions")
        else:
            logger.error(f"Failed to trigger 'Auto Release' workflow: {workflow_result.stderr}")
            if "could not find workflow" in workflow_result.stderr.lower():
                logger.error("Make sure the 'Auto Release' workflow exists in the repository")
                logger.error("Check: https://github.com/{}/actions".format(repo_name))
            raise SystemExit(1)

    except subprocess.CalledProcessError as e:
        logger.error(f"Command execution failed: {e}")
        logger.error(f"Error output: {e.stderr}")
        raise SystemExit(1)
    except Exception as e:
        logger.error(f"Unexpected error in runRelease: {str(e)}")
        raise SystemExit(1)

def searchProjects():
    """搜索GitHub组织下的项目，支持模糊搜索并按更新时间排序"""
    try:
        # 构建gh命令
        org = argsInfo.projectOrg
        search_query = argsInfo.projectName
        
        if search_query:
            # 使用gh命令进行搜索，按pushedAt排序，过滤包含搜索关键词的项目
            jq_filter = f'.[] | select(.name | test("{search_query}"; "i")) | {{name: .name, pushedAt: .pushedAt, url: .url}}'
        else:
            # 获取所有仓库
            jq_filter = '.[] | {name: .name, pushedAt: .pushedAt, url: .url}'

        # 构建gh命令
        gh_cmd = [
            "gh", "repo", "list", org,
            "--limit", "100",
            "--json", "name,pushedAt,url",
            "--jq", jq_filter
        ]
        
        # 执行gh命令
        result = subprocess.run(
            gh_cmd,
            capture_output=True,
            text=True,
            check=True
        )
        
        # 解析输出
        repos = []
        for line in result.stdout.strip().split('\n'):
            if line.strip():
                try:
                    repo_data = json.loads(line)
                    repos.append(repo_data)
                except json.JSONDecodeError:
                    continue
        
        if not repos:
            return
        
        # 按更新时间排序（最新的在前）
        repos.sort(key=lambda x: x['pushedAt'], reverse=True)
        
        # 直接输出结果，不显示总结信息
        for repo in repos:
            name = repo['name']
            
            if argsInfo.quiet:
                # 静默模式，只输出项目名称
                print(name)
            else:
                # 正常模式，输出时间和项目名称
                pushed_at = repo['pushedAt']
                # 格式化日期
                try:
                    from datetime import datetime
                    # 解析UTC时间并转换为本地时间
                    dt = datetime.fromisoformat(pushed_at.replace('Z', '+00:00'))
                    # 转换为本地时间
                    local_dt = dt.astimezone()
                    formatted_date = local_dt.strftime('%Y-%m-%d %H:%M')
                except:
                    formatted_date = pushed_at[:16].replace('T', ' ')
                
                print(f"{formatted_date:<20} {name:<20} {repo['url']}")
        
    except subprocess.CalledProcessError as e:
        if "authentication required" in e.stderr.lower() or "not logged in" in e.stderr.lower():
            logger.error("Not logged in to GitHub")
            logger.error("Please run: gh auth login")
        elif "organization not found" in e.stderr.lower():
            logger.error(f"Organization '{org}' not found or not accessible")
        else:
            logger.error(f"GitHub CLI error: {e.stderr}")
        raise SystemExit(1)
    except Exception as e:
        logger.error(f"Unexpected error in searchProjects: {str(e)}")
        raise SystemExit(1)

def createOrUpdateRepo():
    dir = os.path.expanduser(argsInfo.projectRootDir)
    if not os.path.exists(dir):
        os.makedirs(dir)

    logger.info(f"Tagging project: {dir}, {argsInfo.projectName}")
    os.chdir(dir)

    if not os.path.exists(dir + "/" + argsInfo.projectName):
        createRepo()
        os.chdir(argsInfo.projectName)
        initRepo()
    else:
        os.chdir(argsInfo.projectName)

def main(argv):
    parser = argparse.ArgumentParser(description='Pack for CRP.')
    parser.add_argument('command', nargs='?', default='tag', choices=['tag', 'merge', 'test', 'lasttag', 'release', 'projects'], help='The command type (list or pack)')

    parser.add_argument('--dir', type=str, default=None, help='The project directory')
    parser.add_argument('--org', type=str, default=None, help='The project organization, e.g: linuxdeepin')
    parser.add_argument('--name', type=str, default=None, help='The project name')
    parser.add_argument('--branch', type=str, default=None, help='The project branch')
    parser.add_argument('--tag', type=str, default=None, help='The project tag')
    parser.add_argument('--reviewer', type=str, default=[], nargs='+', help='The project reviewers')
    parser.add_argument('--verbose', action='store_true', help='Show verbose output for git operations')
    parser.add_argument('--quiet', action='store_true', help='Show brief output results')

    if "DEBEMAIL" not in os.environ:
        os.environ["DEBEMAIL"] = argsInfo.debEmail

    args = parser.parse_args()

    if (args.name is not None):
        argsInfo.projectName = args.name
    elif (args.command == 'projects'):
        # projects命令如果没有提供name参数，则清空搜索关键词
        argsInfo.projectName = ""
    if (args.branch is not None):
        argsInfo.projectBranch = args.branch
    if (args.tag is not None):
        argsInfo.projectTag = args.tag
    else:
        argsInfo.autoGeneratedProjectTag = True
    if (args.dir is not None):
        argsInfo.projectRootDir = args.dir
    if (args.org is not None):
        argsInfo.projectOrg = args.org
    reviewers = args.reviewer
    if len(reviewers) > 0:
        argsInfo.projectReviewers = reviewers
    argsInfo.verbose = args.verbose
    argsInfo.quiet = args.quiet

    if (args.command == 'release'):
        # release命令不需要createOrUpdateRepo，直接执行
        runRelease()
    elif (args.command == 'projects'):
        # projects命令不需要createOrUpdateRepo，直接搜索项目
        searchProjects()
    else:
        createOrUpdateRepo()
        if (args.command == 'merge'):
            mergePR()
        elif (args.command == 'test'):
            initTagPR()
            try:
                diff_result = subprocess.run(
                    "git diff HEAD^ HEAD | cat",
                    shell=True,
                    check=True,
                    capture_output=True,
                    text=True
                )
                print(diff_result.stdout)
            except subprocess.CalledProcessError as e:
                logger.error(f"Failed to show diff: {e.stderr}")
        elif (args.command == 'lasttag'):
            lastTag = fetchLastTag()
            logger.info(f"Last Tag: {lastTag}")
        else:
            initTagPR()
            createTagPR()

if(__name__=="__main__"):
    main(sys.argv)
