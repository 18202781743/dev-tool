def runRelease():
    """执行GitHub Auto Release workflow"""
    try:
        # 检查gh命令是否可用
        gh_check = subprocess.run(
            ["gh", "--version"],
            capture_output=True,
            text=True
        )
        if gh_check.returncode != 0:
            logger.error("GitHub CLI (gh) is not installed or not available")
            logger.error("Please install GitHub CLI: https://cli.github.com/")
            raise SystemExit(1)

        # 检查是否已登录GitHub
        auth_check = subprocess.run(
            ["gh", "auth", "status"],
            capture_output=True,
            text=True
        )
        if auth_check.returncode != 0:
            logger.error("Not logged in to GitHub")
            logger.error("Please run: gh auth login")
            raise SystemExit(1)

        # 设置默认仓库
        repo_name = f"{argsInfo.projectOrg}/{argsInfo.projectName}"
        logger.info(f"Setting default repository to {repo_name}")

        set_default_result = subprocess.run(
            ["gh", "repo", "set-default", repo_name],
            capture_output=True,
            text=True
        )
        if set_default_result.returncode != 0:
            logger.warning(f"Could not set default repository: {set_default_result.stderr}")
            logger.info("Continuing with explicit repository specification...")

        # 触发Auto Release workflow
        logger.info(f"Triggering 'Auto Release' workflow for {repo_name}")

        workflow_cmd = ["gh", "workflow", "run", "Auto Release"]
        if set_default_result.returncode != 0:
            workflow_cmd.extend(["--repo", repo_name])

        workflow_result = subprocess.run(
            workflow_cmd,
            capture_output=True,
            text=True
        )

        if workflow_result.returncode == 0:
            logger.info("✅ Successfully triggered 'Auto Release' workflow")
            logger.info("🚀 The workflow will automatically create tags and PRs")
            print(f"\n🎉 Auto Release workflow triggered for {repo_name}!")
            print("📋 You can check the workflow status at:")
            print(f"   https://github.com/{repo_name}/actions")
        else:
            logger.error(f"Failed to trigger 'Auto Release' workflow: {workflow_result.stderr}")
            if "could not find workflow" in workflow_result.stderr.lower():
                logger.error("Make sure the 'Auto Release' workflow exists in the repository")
                logger.error("Check: https://github.com/{}/actions".format(repo_name))
            raise SystemExit(1)

    except subprocess.CalledProcessError as e:
        logger.error(f"Command execution failed: {e}")
        logger.error(f"Error output: {e.stderr}")
        raise SystemExit(1)
    except Exception as e:
        logger.error(f"Unexpected error in runRelease: {str(e)}")
        raise SystemExit(1)

def localCommitTag(repo_path):
    """在本地仓库中更新changelog并提交tag"""
    try:
        # 验证仓库路径
        if not repo_path:
            logger.error("Repository path is required for localcommit command")
            logger.error("Please use --repo-path to specify the local repository path")
            raise SystemExit(1)
            
        repo_path = os.path.expanduser(repo_path)
        if not os.path.exists(repo_path):
            logger.error(f"Repository path does not exist: {repo_path}")
            raise SystemExit(1)
            
        if not os.path.exists(os.path.join(repo_path, '.git')):
            logger.error(f"Not a git repository: {repo_path}")
            raise SystemExit(1) 
            
        # 切换到仓库目录
        original_cwd = os.getcwd()
        os.chdir(repo_path)
        logger.info(f"Working in repository: {repo_path}")
        
        try:
            # 检查仓库状态
            status_result = subprocess.run(
                ["git", "status", "--porcelain"],
                capture_output=True,
                text=True,
                check=True
            )
            
            if status_result.stdout.strip():
                logger.warning("Repository has uncommitted changes:")
                logger.warning(status_result.stdout.strip())
                logger.info("Continuing with changelog update...")
            
            # 设置DEBEMAIL环境变量
            os.environ["DEBEMAIL"] = argsInfo.debEmail
            
            # 获取最新的标签版本作为基准（与tag命令保持一致，优先使用changelog）
            lastTag = findLastTaggedVersion()
            if not lastTag:
                logger.warning("No version found, using default version")
                lastTag = "0.0.0"
            else:
                logger.info(f"Found last tagged version: {lastTag}")
            
            # 确定新的tag版本
            if argsInfo.autoGeneratedProjectTag:
                argsInfo.projectTag = autoGeneratedTagByLastTag(lastTag)
                logger.info(f"Auto-generated tag: {argsInfo.projectTag}")
            else:
                logger.info(f"Using specified tag: {argsInfo.projectTag}")
            
            # 获取commit信息用于changelog
            try:
                commit_result = subprocess.run(
                    ["git", "log", "--pretty=format:%s", "--no-merges", f"{lastTag}..HEAD"],
                    capture_output=True,
                    text=True,
                    check=True
                )
                commitInfo = commit_result.stdout.strip()
                if not commitInfo:
                    commitInfo = f"Release {argsInfo.projectTag}"
                logger.info(f"Changelog entries: {len(commitInfo.splitlines())} commits")
            except subprocess.CalledProcessError:
                commitInfo = f"Release {argsInfo.projectTag}"
                logger.info("No commit history found, using default changelog entry")
            
            # 检查是否存在debian/changelog文件
            changelog_path = os.path.join(repo_path, "debian", "changelog")
            if not os.path.exists(changelog_path):
                logger.warning(f"debian/changelog not found at {changelog_path}")
                logger.info("Creating debian directory and changelog...")
                
                # 创建debian目录
                debian_dir = os.path.join(repo_path, "debian")
                if not os.path.exists(debian_dir):
                    os.makedirs(debian_dir)
                
                # 创建基本的changelog文件
                project_name = argsInfo.projectName or os.path.basename(repo_path)
                initial_changelog = f"""{project_name} ({argsInfo.projectTag}) unstable; urgency=medium

  * Initial release

 -- {argsInfo.debEmail}  {datetime.now().strftime('%a, %d %b %Y %H:%M:%S %z')}
"""
                with open(changelog_path, 'w') as f:
                    f.write(initial_changelog)
                logger.info("Created initial debian/changelog")
            
            # 更新changelog
            logger.info("Updating changelog...")
            
            # 使用dch命令更新changelog
            with subprocess.Popen(
                ["xargs", "-d", "\n", "-I", "{}", "dch", "-v", argsInfo.projectTag, "{}"],
                stdin=subprocess.PIPE,
                text=True,
                cwd=repo_path
            ) as dch_process:
                dch_process.communicate(input=commitInfo)
            
            # 完成changelog编辑
            subprocess.run(
                "dch -r ''",
                shell=True,
                check=True,
                capture_output=True,
                text=True,
                cwd=repo_path
            )
            
            logger.info("Changelog updated successfully")
            
            # 显示changelog的更改内容
            if not argsInfo.quiet:
                print(f"\n📝 Changelog entries for version {argsInfo.projectTag}:")
                print("=" * 60)
                # 显示新增的changelog条目
                changelog_entries = commitInfo.strip().split('\n')
                for entry in changelog_entries:
                    if entry.strip():
                        print(f"  * {entry.strip()}")
                print("=" * 60)
            
            # 提交更改
            logger.info("Committing changes...")
            
            # 添加changelog到暂存区
            subprocess.run(
                ["git", "add", "debian/changelog"],
                check=True,
                capture_output=True,
                text=True,
                cwd=repo_path
            )
            
            # 提交更改
            commit_message = f"chore: bump version to {argsInfo.projectTag}\n\nupdate changelog to {argsInfo.projectTag}"
            subprocess.run(
                ["git", "commit", "-m", commit_message],
                check=True,
                capture_output=True,
                text=True,
                cwd=repo_path
            )
            
            logger.info(f"✅ Successfully committed changelog update for version {argsInfo.projectTag}")
            
            # 显示提交信息
            show_result = subprocess.run(
                ["git", "show", "--stat", "HEAD"],
                capture_output=True,
                text=True,
                cwd=repo_path
            )
            
            if not argsInfo.quiet:
                print(f"\n📋 Commit Details:")
                print(show_result.stdout)
            
            print(f"\n🎉 Local commit completed!")
            print(f"📂 Repository: {repo_path}")
            print(f"🏷️  Version: {argsInfo.projectTag}")
            print(f"💾 Changelog updated and committed locally")
            
        finally:
            # 恢复原始工作目录
            os.chdir(original_cwd)
            
    except subprocess.CalledProcessError as e:
        logger.error(f"Git command failed: {e}")
        if e.stderr:
            logger.error(f"Error output: {e.stderr}")
        raise SystemExit(1)
    except Exception as e:
        logger.error(f"Unexpected error in localCommitTag: {str(e)}")
        raise SystemExit(1)

def searchProjects():
    """搜索GitHub组织下的项目，支持模糊搜索并按更新时间排序"""
    try:
        # 构建gh命令
        org = argsInfo.projectOrg
        search_query = argsInfo.projectName
        
        if search_query:
            # 使用gh命令进行搜索，按pushedAt排序，过滤包含搜索关键词的项目
            jq_filter = f'.[] | select(.name | test("{search_query}"; "i")) | {{name: .name, pushedAt: .pushedAt, url: .url}}'
        else:
            # 获取所有仓库
            jq_filter = '.[] | {name: .name, pushedAt: .pushedAt, url: .url}'

        # 构建gh命令
        gh_cmd = [
            "gh", "repo", "list", org,
            "--limit", "100",
            "--json", "name,pushedAt,url",
            "--jq", jq_filter
        ]
        
        # 执行gh命令
        result = subprocess.run(
            gh_cmd,
            capture_output=True,
            text=True,
            check=True
        )
        
        # 解析输出
        repos = []
        for line in result.stdout.strip().split('\n'):
            if line.strip():
                try:
                    repo_data = json.loads(line)
                    repos.append(repo_data)
                except json.JSONDecodeError:
                    continue
        
        if not repos:
            return
        
        # 按更新时间排序（最新的在前）
        repos.sort(key=lambda x: x['pushedAt'], reverse=True)
        
        # 直接输出结果，不显示总结信息
        for repo in repos:
            name = repo['name']
            
            if argsInfo.quiet:
                # 静默模式，只输出项目名称
                print(name)
            else:
                # 正常模式，输出时间和项目名称
                pushed_at = repo['pushedAt']
                # 格式化日期
                try:
                    from datetime import datetime
                    # 解析UTC时间并转换为本地时间
                    dt = datetime.fromisoformat(pushed_at.replace('Z', '+00:00'))
                    # 转换为本地时间
                    local_dt = dt.astimezone()
                    formatted_date = local_dt.strftime('%Y-%m-%d %H:%M')
                except:
                    formatted_date = pushed_at[:16].replace('T', ' ')
                
                print(f"{formatted_date:<20} {name:<20} {repo['url']}")
        
    except subprocess.CalledProcessError as e:
        if "authentication required" in e.stderr.lower() or "not logged in" in e.stderr.lower():
            logger.error("Not logged in to GitHub")
            logger.error("Please run: gh auth login")
        elif "organization not found" in e.stderr.lower():
            logger.error(f"Organization '{org}' not found or not accessible")
        else:
            logger.error(f"GitHub CLI error: {e.stderr}")
        raise SystemExit(1)
    except Exception as e:
        logger.error(f"Unexpected error in searchProjects: {str(e)}")
        raise SystemExit(1)

def createOrUpdateRepo():
    dir = os.path.expanduser(argsInfo.projectRootDir)
    if not os.path.exists(dir):
        os.makedirs(dir)

    logger.info(f"Tagging project: {dir}, {argsInfo.projectName}")
    os.chdir(dir)

    if not os.path.exists(dir + "/" + argsInfo.projectName):
        createRepo()
        os.chdir(argsInfo.projectName)
        initRepo()
    else:
        os.chdir(argsInfo.projectName)

def main(argv):
    parser = argparse.ArgumentParser(description='Pack for CRP.')
    parser.add_argument('command', nargs='?', default='tag', choices=['tag', 'merge', 'test', 'lasttag', 'release', 'projects', 'tag-local'], help='The command type (list or pack)')

    parser.add_argument('--dir', type=str, default=None, help='The project directory')
    parser.add_argument('--org', type=str, default=None, help='The project organization, e.g: linuxdeepin')
    parser.add_argument('--name', type=str, default=None, help='The project name')
    parser.add_argument('--branch', type=str, default=None, help='The project branch')
    parser.add_argument('--tag', type=str, default=None, help='The project tag')
    parser.add_argument('--reviewer', type=str, default=[], nargs='+', help='The project reviewers')
    parser.add_argument('--repo', type=str, default='.', help='Local repository path for tag-local command')
    parser.add_argument('--verbose', action='store_true', help='Show verbose output for git operations')
    parser.add_argument('--quiet', action='store_true', help='Show brief output results')

    if "DEBEMAIL" not in os.environ:
        os.environ["DEBEMAIL"] = argsInfo.debEmail

    args = parser.parse_args()

    if (args.name is not None):
        argsInfo.projectName = args.name
    elif (args.command == 'projects'):
        # projects命令如果没有提供name参数，则清空搜索关键词
        argsInfo.projectName = ""
    if (args.branch is not None):
        argsInfo.projectBranch = args.branch
    if (args.tag is not None):
        argsInfo.projectTag = args.tag
    else:
        argsInfo.autoGeneratedProjectTag = True
    if (args.dir is not None):
        argsInfo.projectRootDir = args.dir
    if (args.org is not None):
        argsInfo.projectOrg = args.org
    reviewers = args.reviewer
    if len(reviewers) > 0:
        argsInfo.projectReviewers = reviewers
    argsInfo.verbose = args.verbose
    argsInfo.quiet = args.quiet

    if (args.command == 'release'):
        # release命令不需要createOrUpdateRepo，直接执行
        runRelease()
    elif (args.command == 'projects'):
        # projects命令不需要createOrUpdateRepo，直接搜索项目
        searchProjects()
    elif (args.command == 'tag-local'):
        # tag-local命令在指定的本地仓库中执行，不需要createOrUpdateRepo
        localCommitTag(args.repo)
    else:
        createOrUpdateRepo()
        if (args.command == 'merge'):
            mergePR()
        elif (args.command == 'test'):
            initTagPR()
            try:
                diff_result = subprocess.run(
                    "git diff HEAD^ HEAD | cat",
                    shell=True,
                    check=True,
                    capture_output=True,
                    text=True
                )
                print(diff_result.stdout)
            except subprocess.CalledProcessError as e:
                logger.error(f"Failed to show diff: {e.stderr}")
        elif (args.command == 'lasttag'):
            lastTag = fetchLastTag()
            logger.info(f"Last Tag: {lastTag}")
        else:
            initTagPR()
            createTagPR()

